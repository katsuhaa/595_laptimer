#!/usr/bin/env python3
"""tools/web/embed.py - puts web/index.html and web/report.html into the firmware.

Writes firmware/laptimer/src/web/web_assets.h with
  kIndexGz / kIndexGzLen          index.html, gzip (served with Content-Encoding: gzip)
  kReportGz / kReportGzLen        report.html, gzip (GET /report.html: the page alone, fetches its data)
  kReportHead / kReportHeadLen    report.html before the marker <!--LT_DATA--> (not compressed)
  kReportTail / kReportTailLen    report.html after the marker (not compressed)
For GET /report the device streams head + the session's data blocks + tail. The data (about 1.5 MB
for 30 minutes) is made while the log is read, so it cannot be gzip-compressed in flash; compressing
it on the fly would need a deflate state of about 300 KB on the ESP32, and only the page code (a few
percent of the file) could be precompressed. So /report is sent uncompressed, and the downloaded
report_<id>.html is a plain HTML file that the iPhone Files app opens.

Checks (exit 1 with a message): the marker is in report.html exactly once; no page loads anything
from outside (src/href/url()/@import/fetch to http(s):// or //host - D12: no external services).
The output is deterministic (gzip mtime 0), so it changes only when the pages change.
  embed.py [--check]     --check: only verify that web_assets.h is up to date (exit 1 if not)
Python 3.9+ standard library only.
"""
import gzip
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
WEB = os.path.join(ROOT, 'web')
OUT = os.path.join(ROOT, 'firmware', 'laptimer', 'src', 'web', 'web_assets.h')
MARKER = b'<!--LT_DATA-->'
EXTERNAL = re.compile(rb'''(?:\b(?:src|href|action)\s*=\s*["']?\s*(?:https?:)?//)|(?:url\(\s*["']?\s*(?:https?:)?//)|'''
                      rb'''(?:@import)|(?:\bfetch\(\s*["'](?:https?:)?//)''', re.I)


def fail(msg):
    print('FAIL ' + msg)
    sys.exit(1)


def array(name, data):
    lines = ['static const uint8_t %s[] = {' % name]
    for i in range(0, len(data), 24):
        lines.append('  ' + ','.join('%d' % b for b in data[i:i + 24]) + ',')
    lines.append('};')
    lines.append('static const size_t %sLen = %d;' % (name, len(data)))
    return '\n'.join(lines)


def build():
    pages = {}
    for name in ('index.html', 'report.html'):
        with open(os.path.join(WEB, name), 'rb') as f:
            data = f.read()
        m = EXTERNAL.search(data)
        if m:
            line = data[:m.start()].count(b'\n') + 1
            fail('web/%s line %d loads something from outside: %s' % (name, line, m.group(0).decode('utf-8', 'replace')))
        pages[name] = data
    report = pages['report.html']
    if report.count(MARKER) != 1:
        fail('web/report.html must contain %s exactly once' % MARKER.decode())
    head, tail = report.split(MARKER)
    index_gz = gzip.compress(pages['index.html'], compresslevel=9, mtime=0)
    report_gz = gzip.compress(report, compresslevel=9, mtime=0)
    text = '\n'.join([
        '// web_assets.h - GENERATED by tools/web/embed.py from web/index.html and web/report.html.',
        '// Do not edit; run: python3 tools/web/embed.py',
        '// index.html %d bytes (gzip %d), report.html %d bytes (gzip %d; head %d + tail %d sent around the data)'
        % (len(pages['index.html']), len(index_gz), len(report), len(report_gz), len(head), len(tail)),
        '#pragma once',
        '#include <stddef.h>',
        '#include <stdint.h>',
        '',
        'namespace web {',
        'namespace assets {',
        '',
        array('kIndexGz', index_gz),
        '',
        array('kReportGz', report_gz),
        '',
        array('kReportHead', head),
        '',
        array('kReportTail', tail),
        '',
        '}  // namespace assets',
        '}  // namespace web',
        '',
    ])
    sizes = (len(pages['index.html']), len(index_gz), len(report), len(report_gz), len(head), len(tail))
    return text, sizes


def main():
    check = '--check' in sys.argv[1:]
    text, s = build()
    old = None
    if os.path.exists(OUT):
        with open(OUT, 'r', encoding='utf-8') as f:
            old = f.read()
    summary = ('index.html %d B (gzip %d B), report.html %d B (gzip %d B; head %d B + tail %d B), flash %d B'
               % (s[0], s[1], s[2], s[3], s[4], s[5], s[1] + s[3] + s[4] + s[5]))
    if check:
        if old != text:
            fail('%s is not up to date with web/*.html: run python3 tools/web/embed.py' % os.path.relpath(OUT, ROOT))
        print('PASS web_assets.h up to date: ' + summary)
        return
    if old != text:
        with open(OUT, 'w', encoding='utf-8') as f:
            f.write(text)
        print('wrote %s: %s' % (os.path.relpath(OUT, ROOT), summary))
    else:
        print('unchanged %s: %s' % (os.path.relpath(OUT, ROOT), summary))
    print('PASS embed')


if __name__ == '__main__':
    main()
