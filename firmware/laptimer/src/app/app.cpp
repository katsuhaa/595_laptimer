struct LinkSink : lt::mlink::Sink {
  void onCan(uint8_t bus, uint8_t ext, uint32_t id, uint8_t dlc, const uint8_t* data, uint32_t nowMs) override {
    {
      Lock l(g_vehMu);
      g_veh.onFrame(bus, ext, id, dlc, data, nowMs);
    }
    if (g_set.bleOn) hw::bleSendCan(id, data, dlc, nowMs);
    if (g_set.canRawLog && logger::isOpen()) {
      int64_t utcMs = 0;
      if (!timeNowUtcMs(nowMs, &utcMs)) utcMs = nowMs;
      char line[80];
      const int n = lt::csvlog::canLine(line, sizeof line, utcMs, bus ? 'B' : 'C', id, dlc, data);
      if (n > 0) logger::write(logger::S_CAN, line, static_cast<size_t>(n));
    }
  }
};

void linkTask(void*) {
  static LinkSink sink;
  static lt::mlink::Parser parser(&sink);
  hw::linkBegin();
  for (;;) {
    const uint32_t now = millis();
    hw::linkPoll(parser, now);  // feeds the parser: onCan -> g_veh (same task)
    lt::VehValues v;
    lt::LightInfo li;
    {
      Lock l(g_vehMu);
      g_veh.getLinkValues(parser, now, &v);
      g_veh.lightInfo(&li, now);
    }
    lt::mlink::Stats st;
    parser.getStats(&st);
    {
      Lock l(g_mu);
      g_live.veh = v;
      g_live.linkUp = v.linkUp;
      g_live.canPerSec = st.canPerSec;
      g_live.lightOn = li.have && li.on;
    }
    vTaskDelay(pdMS_TO_TICKS(2));
  }
}

// ------------------------------------------------------------------------------------------- imu task
void imuTask(void*) {
  TickType_t last = xTaskGetTickCount();
  uint32_t k = 0;
  for (;;) {
    vTaskDelayUntil(&last, pdMS_TO_TICKS(5));  // 200 Hz
    float ax, ay, az, gx, gy, gz;
    if (!hw::imuRead(&ax, &ay, &az, &gx, &gy, &gz)) continue;
    const uint32_t now = millis();
    ++k;
    bool speedOk;
    float kmh;
    {
      Lock l(g_mu);
      speedOk = g_live.speedOk;
      kmh = g_live.speedKmh;
    }
    if (k % 4 == 0) {  // ImuCal constants are for 50 Hz (round gauge)
      g_imu.sample(ax, ay, az, speedOk, kmh, now);
      if (g_imu.stillNow()) g_imu.updateGyroBias(gx, gy, gz);
    }
    float lon, lat, vert;
    g_imu.carOf(ax, ay, az, &lon, &lat, &vert);  // car frame, scaled, gravity removed (round gauge imu::car)
    const float yaw = g_imu.yawDps(gx, gy, gz);
    portENTER_CRITICAL(&g_imuMux);
    g_imuAcc.lon += lon;
    g_imuAcc.lat += lat;
    g_imuAcc.vert += vert;
    g_imuAcc.yaw += yaw;
    g_imuAcc.n++;
    portEXIT_CRITICAL(&g_imuMux);
    if (logger::isOpen()) {
      int64_t utcMs = 0;
      if (!timeNowUtcMs(now, &utcMs)) utcMs = now;
      lt::csvlog::ImuRow r = {utcMs, ax, ay, az, gx, gy, gz};
      char line[96];
      const int n = lt::csvlog::imuLine(line, sizeof line, r);
      if (n > 0) logger::write(logger::S_IMU, line, static_cast<size_t>(n));
    }
    if (g_set.bleOn) hw::bleSendImu(lon, lat, vert, yaw, now);  // paced inside (20 Hz, round gauge RC_IMU_HZ)
    if (k % 200 == 0) {
      Lock l(g_mu);
      g_live.imuOk = true;
      g_live.imuLevel = g_imu.levelOk();
      g_live.imuForward = g_imu.forwardOk();
    }
  }
}

