void selfTest(bool touchOk, bool imuOk, bool rtcOk, bool sdOk) {
  char v[48];
  setRow(0, SelfTestRow::Wait, "GNSS", "設定中");
  // XTSD: capacity and a 1 MB write/read (計画 §3.4: 2 GB 品は約 1.8 GB)
  if (sdOk) {
    float w = 0, r = 0;
    const char* why = "";
    const bool ok = hw::sdSelfTest(&w, &r, &why);
    snprintf(v, sizeof v, ok ? "%.2f GB 書込 %.1f 読込 %.1f MB/s" : "%.2f GB %s", hw::sdTotalBytes() / 1e9, ok ? w : 0.0f,
             ok ? r : 0.0f);
    if (!ok) snprintf(v, sizeof v, "%.2f GB %s", hw::sdTotalBytes() / 1e9, why);
    setRow(1, ok ? SelfTestRow::Pass : SelfTestRow::Fail, "XTSD", v);
  } else {
    setRow(1, SelfTestRow::Fail, "XTSD", "マウント不可 Web で確認");  // the page offers the format
  }
  setRow(3, imuOk ? SelfTestRow::Pass : SelfTestRow::Fail, "IMU", imuOk ? "QMI8658" : "応答なし");
  setRow(4, touchOk ? SelfTestRow::Pass : SelfTestRow::Fail, "TOUCH", touchOk ? "FT6336" : "応答なし");
  setRow(5, rtcOk ? SelfTestRow::Pass : SelfTestRow::Fail, "RTC", rtcOk ? "RTC" : "RTC 応答なし");
  setRow(6, SelfTestRow::Info, "BLE", g_set.bleOn ? "待受中" : "切");
  setRow(7, SelfTestRow::Info, "WiFi", "停止中のみ");
  const uint32_t t0 = millis();
  bool gnssDone = false, canDone = false;
  while (millis() - t0 < 30000 && !(gnssDone && canDone)) {
    Live s;
    liveGet(&s);
    const uint32_t dt = millis() - t0;
    if (!gnssDone) {
      if (s.pvtPerSec >= 20) {
        snprintf(v, sizeof v, "%u Hz 衛星 %u hAcc %.1f m", static_cast<unsigned>(s.pvtPerSec), s.fix.numSV,
                 s.fix.hAcc_mm * 0.001f);
        setRow(0, SelfTestRow::Pass, "GNSS", v);
        gnssDone = true;
      } else if (dt > 20000) {
        snprintf(v, sizeof v, s.pvtPerSec ? "%u Hz（25 Hz にならない）" : "受信なし", static_cast<unsigned>(s.pvtPerSec));
        setRow(0, SelfTestRow::Fail, "GNSS", v);
        gnssDone = true;
      }
    }
    if (!canDone) {
      if (s.canPerSec > 0) {
        snprintf(v, sizeof v, "C6 の箱 %u フレーム/秒", static_cast<unsigned>(s.canPerSec));
        setRow(2, SelfTestRow::Pass, "CAN", v);
        canDone = true;
      } else if (dt > 5000) {
        setRow(2, SelfTestRow::Fail, "CAN", s.linkUp ? "CAN なし" : "受信なし");
        canDone = true;
      } else {
        setRow(2, SelfTestRow::Wait, "CAN", "待機中");
      }
    }
    vTaskDelay(pdMS_TO_TICKS(250));
  }
  Lock l(g_mu);
  bool all = true;
  for (int i = 0; i < 6; ++i) all = all && g_live.selftest[i].state == SelfTestRow::Pass;
  g_live.selftestAllPass = all;
}

void storageStats(uint32_t nowMs) {
  static uint32_t lastUsed = 0;
  static uint64_t used = 0;
  if (!hw::sdMounted()) return;
  if (lastUsed == 0 || nowMs - lastUsed > 30000) {
    lastUsed = nowMs;
    used = hw::sdUsedBytes();
  }
  const uint64_t total = hw::sdTotalBytes();
  logger::Stats ls;
  logger::stats(&ls);
  g_store.setSpace(static_cast<int64_t>(total), static_cast<int64_t>(total - used));
  static bool wasOpen = false;
  static uint32_t openMs = 0;
  if (ls.open && !wasOpen) openMs = nowMs;
  wasOpen = ls.open;
  if (ls.open) {  // the measured data rate of the open session (kept after it closes)
    int64_t bytes = 0;
    for (int i = 0; i < logger::S_COUNT; ++i) bytes += ls.bytes[i];
    g_store.setRecorded(bytes, static_cast<int64_t>(nowMs - openMs));
  }
  Lock l(g_mu);
  g_live.sdOk = true;
  g_live.sdTotal = total;
  g_live.sdUsed = used;
  g_live.remainHours = g_store.hoursLeft();
  g_live.storageWarn = g_store.low();
  g_live.undownloaded = sessions::undownloaded();
}

// Capacity management (実装計画 5-6): keep at least 2 hours free by deleting downloaded sessions, oldest first
void manageCapacity() {
  const int64_t need = g_store.shortfallFor(2.0f);
  if (need <= 0) return;
  const int n = sessions::count();
  struct Work {
    lt::StoreSession list[sessions::kMax];
    char ids[sessions::kMax][16];
    int order[sessions::kMax];
  };
  app::PsBuf wb(sizeof(Work));
  if (!wb.ok()) return;
  lt::StoreSession* list = wb.as<Work>()->list;
  char (*ids)[16] = wb.as<Work>()->ids;
  int* order = wb.as<Work>()->order;
  char active[16];
  {
    Lock l(g_mu);
    strncpy(active, g_live.sessionId, sizeof active);
  }
  // oldest first for the plan
  for (int i = 0; i < n; ++i) {
    sessions::Info s;
    sessions::get(n - 1 - i, &s);
    strncpy(ids[i], s.id, sizeof ids[i] - 1);
    list[i] = lt::StoreSession{};
    list[i].id = ids[i];
    list[i].downloaded = s.downloaded;
    list[i].active = strcmp(s.id, active) == 0;
    list[i].bytes = static_cast<int64_t>(s.bytes);
  }
  const lt::DeletePlan p = g_store.plan(list, n, need, order, sessions::kMax);
  for (int k = 0; k < p.count; ++k) {
    sessions::Info s;
    sessions::get(n - 1 - order[k], &s);
    Serial.printf("capacity: deleting downloaded session %s\n", s.id);
    sessions::removeSession(s.id);
  }
  if (p.count) sessions::rescan();
}

// Free memory on the serial output (once a minute): the internal RAM is shared by Wi-Fi, BLE and the task stacks
void memReport(uint32_t nowMs) {
  static uint32_t last = 0;
  if (last && nowMs - last < 60000) return;
  last = nowMs ? nowMs : 1;
  Serial.printf("mem: internal %u KB free (lowest %u KB, largest block %u KB), PSRAM %u KB free\n",
                static_cast<unsigned>(heap_caps_get_free_size(MALLOC_CAP_INTERNAL) / 1024),
                static_cast<unsigned>(heap_caps_get_minimum_free_size(MALLOC_CAP_INTERNAL) / 1024),
                static_cast<unsigned>(heap_caps_get_largest_free_block(MALLOC_CAP_INTERNAL) / 1024),
                static_cast<unsigned>(heap_caps_get_free_size(MALLOC_CAP_SPIRAM) / 1024));
}

void houseTask(void* arg) {
  const uint32_t flags = reinterpret_cast<uint32_t>(arg);
  memReport(millis());
  selfTest(flags & 1, flags & 2, flags & 4, flags & 8);
  uint32_t lastSave = millis();
  uint32_t stillSince = 0;
  for (;;) {
    const uint32_t now = millis();
    memReport(now);
    if (g_reloadConfig) {
      g_reloadConfig = false;
      // taken in one step: a change that arrives while loading is kept for the next round
      const uint32_t mask = __atomic_exchange_n(&g_reloadMask, 0u, __ATOMIC_SEQ_CST);
      if (mask) loadConfigs(mask);
    }
    if (g_sessionsDirty) {
      g_sessionsDirty = false;
      sessions::rescan();
    }
    if (g_sessionClosed && !logger::isOpen()) {
      g_sessionClosed = false;
      sessions::rescan();
      manageCapacity();
    }
    storageStats(now);
    // NVS: a setting changed; or the ODO / track time moved and the car has stood still for 3 s (the key may go
    // off at any moment); or every 5 minutes while it moves
    {
      Live s;
      liveGet(&s);
      const bool still = !s.speedOk || s.speedKmh < 2.0f;
      if (!still) {
        stillSince = 0;
      } else if (!stillSince) {
        stillSince = now ? now : 1;
      }
      const bool moved = s.odoMm != g_set.odoMm || s.trackMs != g_set.trackMs;
      if (g_settingsDirty || (moved && stillSince && now - stillSince >= 3000) || (moved && now - lastSave > 300000)) {
        g_settingsDirty = false;  // before the copy: a change made during the save is saved next round
        settings::Settings copy;
        {
          Lock l(g_mu);  // the ui task changes g_set under the same lock
          g_set.odoMm = s.odoMm;
          g_set.trackMs = s.trackMs;
          g_imu.exportCal(g_set.imuCal);
          g_set.imuCalOk = s.imuLevel ? 1 : 0;
          copy = g_set;
        }
        settings::save(copy);
        lastSave = now;
      }
    }
    {
      net::Status ns;
      net::status(&ns);
      char v[48];
      net::Names nn;
      net::names(&nn);
      if (ns.connected) snprintf(v, sizeof v, "%s %s", ns.ssid, ns.ip);
      else if (!nn.count) snprintf(v, sizeof v, "未登録（設定 → Wi-Fi）");
      else snprintf(v, sizeof v, "%s", ns.enabled ? "接続中…" : "停止中のみ");
      setRow(7, SelfTestRow::Info, "WiFi", v);
      setRow(6, SelfTestRow::Info, "BLE", !g_set.bleOn ? "切" : hw::bleConnected() ? "RaceChrono 接続" : "待受中");
      Lock l(g_mu);
      g_live.bleOn = g_set.bleOn;
      g_live.bleConnected = hw::bleConnected();
    }
    vTaskDelay(pdMS_TO_TICKS(1000));
  }
}

