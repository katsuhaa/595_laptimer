// The main log row of one epoch without the lap fields (timing::onRow fills those)
void buildRow(const lt::GnssFix& g, const lt::VehValues& v, const ImuAcc& imu, lt::csvlog::MainRow* out) {
  lt::csvlog::MainRow& r = *out;
  r = lt::csvlog::MainRow{};
  r.utcOk = g.timeOk;
  r.utcMs = g.utcUs / 1000;
  r.posOk = g.fixOk;
  r.latE7 = g.lat;
  r.lonE7 = g.lon;
  r.altOk = g.fixOk && g.fixType >= 3;
  r.altM = static_cast<float>(g.hMSL) * 0.001f;
  r.speedOk = g.fixOk;
  r.speedKmh = static_cast<float>(g.gSpeed) * 0.0036f;
  r.headingOk = g.fixOk;
  r.headingDeg = static_cast<float>(g.headMot) * 1e-5f;
  r.haccOk = true;
  r.haccM = static_cast<float>(g.hAcc_mm) * 0.001f;
  r.satsOk = true;
  r.sats = g.numSV;
  r.fixOk = true;
  r.fix = g.fixOk ? (g.fixType >= 3 ? 3 : 2) : 0;
  r.imuOk = imu.n > 0;
  r.yawOk = imu.n > 0;
  if (imu.n > 0) {
    r.lonG = imu.lon / static_cast<float>(imu.n);
    r.latG = imu.lat / static_cast<float>(imu.n);
    r.vertG = imu.vert / static_cast<float>(imu.n);
    r.yawDps = imu.yaw / static_cast<float>(imu.n);
  }
  r.rpmOk = v.rpmOk;
  r.rpm = v.rpm;
  r.throttleOk = v.throttleOk;
  r.throttlePct = v.throttlePct;
  r.speedCanOk = v.speedOk;
  r.speedCanKmh = v.speedKmh;
  r.waterOk = v.waterOk;
  r.waterC = v.waterC;
  r.fuelOk = v.fuelOk;
  r.fuelPct = v.fuelPct;
  r.boostOk = v.boostOk;
  r.boostBar = v.boostBar;
  r.gearOk = v.gearOk;
  r.gear = v.gear;
}

// Main log row and VBO line of one epoch
void writeRow(const lt::GnssFix& g, const lt::VehValues& v, const lt::csvlog::MainRow& r) {
  static char line[512];  // gnss task only
  int n = lt::csvlog::mainLine(line, sizeof line, r);
  if (n > 0) logger::write(logger::S_MAIN, line, static_cast<size_t>(n));
  float extra[kVboChN] = {v.rpmOk ? static_cast<float>(v.rpm) : 0.0f, v.throttleOk ? v.throttlePct : 0.0f,
                          v.waterOk ? v.waterC : 0.0f, v.fuelOk ? v.fuelPct : 0.0f};
  lt::VboSample s = {};
  s.sats = g.numSV;
  s.utcMsOfDay = static_cast<uint32_t>((g.utcUs / 1000) % 86400000LL);
  s.latE7 = g.lat;
  s.lonE7 = g.lon;
  s.speedKmh = r.speedKmh;
  s.headingDeg = r.headingDeg;
  s.heightM = r.altM;
  s.extra = extra;
  n = lt::vboLine(line, sizeof line, s, kVboChN);
  if (n > 0) logger::write(logger::S_VBO, line, static_cast<size_t>(n));
}

void onLap(const timing::LapRow& row) {
  g_sessLaps = row.lapNo;
  if (g_sessBestMs == 0 || row.lapMs < g_sessBestMs) {
    g_sessBestMs = row.lapMs;
    g_sessBestLap = row.lapNo;
  }
  int64_t sec[lt::kMaxSectors + 1];
  for (int i = 0; i < row.numSplits; ++i) sec[i] = row.splitMs[i];
  if (!g_logOpen) return;
  char line[160];
  if (lt::csvlog::lapsLine(line, sizeof line, row.lapNo, row.startUtcMs, row.endUtcMs, row.lapMs, sec, row.numSplits) > 0) {
    logger::lapLine(line);
  }
  buildMeta(false, row.endUtcMs);
  logger::meta(g_meta);
}

// "Near a course" of the last fix, kept for 10 s without a fix (a bridge or a roof does not end it)
bool g_near = false;
uint32_t g_nearMs = 0;
constexpr uint32_t kNearHoldMs = 10000;
uint32_t g_driveMs = 0;  // millis() of the last DriveState update
bool g_odoSetPending = false;  // the owner's ODO from the Web page (under g_mu), applied by the gnss task
int64_t g_odoSetMm = 0;

// DriveState (gnss task only): every epoch, and every 100 ms when no NAV-PVT arrives (GNSS missing)
void driveUpdate(uint32_t nowMs, const lt::VehValues& v, bool gnssOk, float gnssKmh) {
  if (nowMs - g_nearMs > kNearHoldMs) g_near = false;
  lt::DriveInput in;
  in.nowMs = nowMs;
  in.canSpeedOk = v.speedOk;
  in.canSpeedKmh = v.speedKmh;
  in.gnssSpeedOk = gnssOk;
  in.gnssSpeedKmh = gnssKmh;
  in.nearCourse = g_near;
  in.courseSession = g_sessOpen && strcmp(g_sessCid, "street") != 0;
  in.lapRunning = g_sessOpen && g_courseOn && timing::lapRunning();
  {
    Lock l(g_mu);
    if (g_odoSetPending) {
      g_odoSetPending = false;
      g_drive.setOdometerMm(g_odoSetMm);
      g_settingsDirty = true;
    }
  }
  const uint32_t ev = g_drive.update(in);
  g_driveMs = nowMs;
  // openSession waits for the files (time from GNSS or RTC, the logger done with the previous ones) while 記録 is on:
  // retried at every update while the state says "open"
  if ((ev & lt::kDrvSessionOpen) || (g_drive.sessionOpen() && !g_sessOpen)) openSession(nowMs);
  if ((ev & lt::kDrvSessionClose) || (g_sessOpen && !g_drive.sessionOpen())) closeSession(nowMs);
  if (g_sessOpen && g_logOpen && !g_recording) closeLog(nowMs);  // 記録 off: files closed, timing goes on
  if (g_sessOpen && !g_logOpen && g_recording) openLog(nowMs);   // 記録 on while driving: new files
  net::setAllowed(g_drive.wifiAllowed() && !g_sessOpen);

  Lock l(g_mu);
  g_live.touchEnabled = g_drive.touchEnabled();
  g_live.stopped = g_drive.stopped();
  g_live.wifiAllowed = g_drive.wifiAllowed();
  g_live.checklistVisible = g_drive.checklistVisible();
  g_live.screen = g_drive.screen();
  g_live.speedOk = g_drive.speedOk();
  g_live.speedKmh = g_drive.speedKmh();
  g_live.odoKm = g_drive.odometerKm();
  g_live.trackHours = g_drive.trackHours();
  g_live.odoMm = g_drive.odometerMm();
  g_live.trackMs = g_drive.trackMs();
  g_live.sessionOpen = g_logOpen;  // "being recorded" (the web never deletes it; the laps page shows its time)
  strncpy(g_live.sessionId, g_logOpen ? g_sessId : "", sizeof g_live.sessionId - 1);
  // the clock also without NAV-PVT (RTC time when the GNSS is missing)
  g_live.timeOk = g_clock.nowUtcMs(nowMs, &g_live.utcMsAtFix);
  g_live.utcBaseMs = nowMs;
}

void driveTick(uint32_t nowMs) {
  lt::VehValues v;
  vehGet(&v);
  driveUpdate(nowMs, v, false, 0.0f);
}

void onFix(const lt::GnssFix& g, uint32_t nowMs) {
  g_clock.onFix(g);
  static bool rtcSynced = false;
  static uint32_t rtcSyncMs = 0;
  if (g.timeOk && g.timeResolved && (!rtcSynced || nowMs - rtcSyncMs > 600000)) {
    if (hw::rtcSet(static_cast<uint32_t>(g.utcUs / 1000000))) {
      rtcSynced = true;
      rtcSyncMs = nowMs;
    }
  }
  lt::VehValues v;
  vehGet(&v);
  bool nearNow = false;
  updateCourse(g, nowMs, &nearNow);
  if (g.fixOk) {
    g_near = nearNow;
    g_nearMs = nowMs;
  }
  const float kmh = static_cast<float>(g.gSpeed) * 0.0036f;
  driveUpdate(nowMs, v, g.fixOk, kmh);

  ImuAcc imu;
  portENTER_CRITICAL(&g_imuMux);
  imu = g_imuAcc;
  g_imuAcc = ImuAcc{};
  portEXIT_CRITICAL(&g_imuMux);

  if (g_sessOpen) {
    lt::csvlog::MainRow r;
    buildRow(g, v, imu, &r);
    if (g_courseOn) {
      timing::LapRow row;
      const uint32_t tev = timing::onRow(&r, &row);
      if (tev & lt::kEvLap) onLap(row);
      if (tev & lt::kEvBest) {
        static uint8_t* blob = nullptr;
        constexpr size_t kCap = 96 * 1024;
        if (!blob) blob = static_cast<uint8_t*>(heap_caps_malloc(kCap, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT));
        const size_t n = blob ? timing::bestBlob(blob, kCap) : 0;
        if (n) logger::bestLap(g_course.id, blob, n);
      }
    }
    if (g.fixOk && kmh > g_sessMaxKmh) g_sessMaxKmh = kmh;
    if (v.rpmOk && v.rpm > g_sessMaxRpm) g_sessMaxRpm = v.rpm;
    if (g_logOpen) writeRow(g, v, r);
  }
  if (g_set.bleOn) hw::bleSendGps(g);

  lt::ChecklistSignals sig;
  sig.sportOk = v.sportOk;
  sig.sport = v.sport;
  sig.bleSubscribed = hw::bleConnected();
  Lock l(g_mu);
  g_live.gnssUp = true;
  g_live.fix = g;
  g_live.fixMs = nowMs;
  g_live.timeOk = g_clock.nowUtcMs(nowMs, &g_live.utcMsAtFix);
  g_live.utcBaseMs = nowMs;
  g_live.maxKmh = g_sessMaxKmh;
  g_live.maxRpm = g_sessMaxRpm;
  g_live.checklist = lt::evaluateChecklist(g_chkCfg, sig);
  if (imu.n > 0) {
    g_live.lonG = imu.lon / static_cast<float>(imu.n);
    g_live.latG = imu.lat / static_cast<float>(imu.n);
    g_live.vertG = imu.vert / static_cast<float>(imu.n);
    g_live.yawDps = imu.yaw / static_cast<float>(imu.n);
  }
}

void gnssTask(void*) {
  hw::gnssBegin();
  static uint8_t buf[2048];
  static lt::ubx::Parser p(40);  // 25 Hz epochs: gaps counted against 40 ms
  for (;;) {
    const uint32_t now = millis();
    const size_t n = hw::gnssPoll(buf, sizeof buf);
    if (n) {
      logger::write(logger::S_UBX, buf, n);
      p.feed(buf, n, now);
    }
    p.tick(now);
    lt::GnssFix g;
    while (p.takeFix(&g)) onFix(g, now);
    if (now - g_driveMs >= 100) driveTick(now);  // no NAV-PVT (GNSS missing): CAN speed, timers
    {
      Lock l(g_mu);
      g_live.pvtPerSec = p.counters().pvtPerSec;
      g_live.missedEpochs = p.counters().missedEpochs;
      if (now - g_live.fixMs > 2000) g_live.gnssUp = false;
      hw::GnssStatus st;
      hw::gnssStatus(&st);
      g_live.gnssConfigured = st.configured;
      g_live.gnssBaud = st.baud;
    }
    vTaskDelay(pdMS_TO_TICKS(n ? 1 : 4));
  }
}

