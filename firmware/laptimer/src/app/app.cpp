bool writeConfigFile(const char* name, const char* text, int len) {
  char path[48], tmp[52];
  snprintf(path, sizeof path, "/config/%s", name);
  snprintf(tmp, sizeof tmp, "%s.tmp", path);
  if (!hw::sdLock(3000)) return false;
  fs::FS& fs = hw::sd();
  fs.mkdir("/config");
  bool ok = false;
  fs::File f = fs.open(tmp, FILE_WRITE);
  if (f) {
    ok = f.write(reinterpret_cast<const uint8_t*>(text), static_cast<size_t>(len)) == static_cast<size_t>(len);
    f.close();
  }
  if (ok) {
    fs.remove(path);
    ok = fs.rename(tmp, path);
  }
  hw::sdUnlock();
  if (ok) hookConfigChanged(name);
  return ok;
}

