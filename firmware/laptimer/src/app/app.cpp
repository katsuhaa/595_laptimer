// A session = the car moving (DriveState): lap timing restarts with it. Its files are written while 記録 is on
// (g_logOpen); switching 記録 off closes the files and the timing goes on, switching it on opens new files.
bool openLog(uint32_t nowMs) {
  int64_t utcMs = 0;
  if (!timeNowUtcMs(nowMs, &utcMs)) return false;  // no time yet (GNSS or RTC): tried again with the next update
  lt::csvlog::sessionId(g_sessId, sizeof g_sessId, utcMs, g_set.tzMin);
  g_sessStartUtcMs = utcMs;
  g_sessMaxKmh = 0;
  g_sessMaxRpm = 0;
  g_sessLaps = 0;
  g_sessBestLap = 0;
  g_sessBestMs = 0;
  lt::gtime::DateTime dt;
  lt::gtime::toLocal(utcMs / 1000, 0, &dt);  // VBO "File created" is UTC (RaceChrono writes UTC)
  const lt::VboDateTime created = {dt.year, dt.month, dt.day, dt.hour, dt.min, dt.sec};
  lt::vboHeader(g_hdrVbo, sizeof g_hdrVbo, created, kVboCh, kVboChN, "595 laptimer");
  buildMeta(false, utcMs);
  logger::OpenInfo o = {};
  strncpy(o.id, g_sessId, sizeof o.id - 1);
  strncpy(o.cid, g_sessCid, sizeof o.cid - 1);
  o.canRaw = g_set.canRawLog != 0;
  o.mainHeader = lt::csvlog::kMainHeader;
  o.vboHeader = g_hdrVbo;
  o.imuHeader = lt::csvlog::kImuHeader;
  o.canHeader = lt::csvlog::kCanHeader;
  o.lapsHeader = lt::csvlog::kLapsHeader;
  o.metaJson = g_meta;
  if (!logger::requestOpen(o)) return false;  // the previous files are still being closed: next update
  g_logOpen = true;
  Serial.printf("session files: %s %s\n", g_sessId, g_sessCid);
  return true;
}

void closeLog(uint32_t nowMs) {
  if (!g_logOpen) return;
  int64_t utcMs = g_sessStartUtcMs;
  timeNowUtcMs(nowMs, &utcMs);
  static char finalMeta[1024];
  buildMeta(true, utcMs);
  memcpy(finalMeta, g_meta, sizeof finalMeta);
  logger::requestClose(finalMeta);
  g_logOpen = false;
  g_sessionClosed = true;
  Serial.printf("session files closed: %s laps %d\n", g_sessId, g_sessLaps);
}

void openSession(uint32_t nowMs) {
  if (g_courseOn) {
    strncpy(g_sessCid, g_course.id, sizeof g_sessCid - 1);
    strncpy(g_sessName, g_course.name, sizeof g_sessName - 1);
  } else {
    strcpy(g_sessCid, "street");
    g_sessName[0] = 0;
  }
  if (g_recording && !openLog(nowMs)) return;  // files first (needs the time); else tried again next update
  if (g_courseOn) timing::newSession();
  g_sessOpen = true;
}

void closeSession(uint32_t nowMs) {
  if (!g_sessOpen) return;
  closeLog(nowMs);
  g_sessOpen = false;
  if (g_courseOn) timing::endSession();
  g_settingsDirty = true;  // odometer and track time
}

