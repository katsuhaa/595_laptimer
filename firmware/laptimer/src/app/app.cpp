// ------------------------------------------------------------------------------------------- course
// Activates course idx with its best lap (/best/<id>.bin). false: not activated (the card was busy: the caller
// tries again with the next fix, so a stored best lap is never mistaken for "none" and overwritten)
bool loadBestAndActivate(int idx) {
  timing::Course c = {};
  {
    Lock l(g_mu);
    if (idx < 0 || idx >= g_courses->count()) return false;
    const lt::Course& src = g_courses->course(idx);
    strncpy(c.id, src.id, sizeof c.id - 1);
    strncpy(c.name, src.name, sizeof c.name - 1);
    if (!g_courses->buildCourseDef(idx, &c.def)) return false;
    lt::Plane pl;
    g_courses->initPlane(idx, &pl);
    c.centerLatE7 = pl.lat0E7();
    c.centerLonE7 = pl.lon0E7();
  }
  static uint8_t* best = nullptr;  // gnss task only
  constexpr size_t kBestCap = 96 * 1024;
  if (!best) best = static_cast<uint8_t*>(heap_caps_malloc(kBestCap, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT));
  size_t n = 0;
  if (hw::sdMounted() && best) {
    // short wait: the gnss task must not stall (its UART buffer holds about 1.6 s)
    if (!hw::sdLock(300)) return false;
    char path[48];
    snprintf(path, sizeof path, "/best/%s.bin", c.id);
    fs::File f = hw::sd().open(path, FILE_READ);
    if (f) {
      n = f.read(best, kBestCap);
      f.close();
    }
    hw::sdUnlock();
  }
  timing::setCourse(&c, n ? best : nullptr, n);
  g_course = c;
  g_courseOn = true;
  g_courseIdx = idx;
  Serial.printf("course: %s (%s), best lap file %u bytes\n", c.id, c.name, static_cast<unsigned>(n));
  return true;
}

void updateCourse(const lt::GnssFix& g, uint32_t nowMs, bool* near) {
  *near = false;
  if (!g.fixOk) return;
  int idx;
  float dist = 0;
  {
    Lock l(g_mu);
    idx = g_courses->nearest(g.lat, g.lon, lt::kNearCourseM, &dist);
  }
  *near = idx >= 0;
  if (g_sessOpen) {
    // The course of an open session does not change; but a street session near a course (it began before the
    // first fix, on CAN speed and RTC time, or on the way to the circuit) ends here: the next update opens a
    // session on the course
    if (idx >= 0 && !g_courseOn && strcmp(g_sessCid, "street") == 0 && loadBestAndActivate(idx)) closeSession(nowMs);
    return;
  }
  if (g_courseReload) {
    // courses.json changed (upload, gate edit, course from a VBO): the indexes and the lines may differ
    g_courseReload = false;
    if (g_courseOn) {
      timing::setCourse(nullptr, nullptr, 0);
      g_courseOn = false;
      g_courseIdx = -1;
    }
  }
  if (!g_courseOn && idx >= 0) {
    loadBestAndActivate(idx);  // false (card busy): again with the next fix
  } else if (g_courseOn) {
    float d;
    {
      Lock l(g_mu);
      d = g_courseIdx < g_courses->count() ? g_courses->distanceM(g_courseIdx, g.lat, g.lon) : 1e9f;
    }
    if (d > kCourseOffM) {
      timing::setCourse(nullptr, nullptr, 0);
      g_courseOn = false;
      g_courseIdx = -1;
    }
  }
}

